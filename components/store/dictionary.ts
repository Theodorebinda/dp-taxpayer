function normalizeKey(input: string): string {
  return input.toLowerCase().replace(/[\s\-_]/g, "");
}

export default function translate(word: string, isPlural: boolean = false) {
  const normalizedKey = normalizeKey(String(word).trim());
  const traduction = dictionnaire[normalizedKey];
  if (!traduction) return word;
  return isPlural ? traduction.plural : traduction.single;
}
